#!/usr/bin/env bash
# One-time history rewrite that drops analysis/ and docs/screenshots/ from every
# commit (docs/history-slim.md). It prepares everything in WORK and NEVER pushes:
# it prints the push commands for the runbook's push step.
#
#   scripts/history-slim/rewrite.sh WORK            # WORK must not exist yet
#   URL=/path/to/mirror.git scripts/history-slim/rewrite.sh WORK   # dry run
#
# Needs git-filter-repo (brew install git-filter-repo) and bash 4+.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
url=${URL:-https://github.com/CardBoardStudio/drawing_board.git}
work=${1:?usage: rewrite.sh WORK}
[ ! -e "$work" ] || { echo "$work already exists" >&2; exit 1; }
mkdir -p "$work"
work=$(cd "$work" && pwd)

# 1. Untouched backup and a bundle of every branch and tag (the rollback source).
git clone --quiet --mirror "$url" "$work/backup.git"
git -C "$work/backup.git" bundle create "$work/drawing_board-pre-slim.bundle" --branches --tags
git -C "$work/backup.git" for-each-ref --format='%(objectname) %(refname)' refs/heads refs/tags > "$work/pre-slim-refs.txt"

# 2. Rewrite a second mirror. GitHub's read-only refs/pull/* cannot be pushed, so drop them.
git clone --quiet --mirror "$work/backup.git" "$work/rewrite.git"
cd "$work/rewrite.git"
git for-each-ref --format='%(refname)' refs/pull | while read -r ref; do git update-ref -d "$ref"; done
git filter-repo --force --invert-paths --paths-from-file "$here/paths.txt"
git reflog expire --expire=now --all
git gc --quiet --prune=now --aggressive

# 3. Commit ids cited in tracked files (study baselines, audits) follow the rewrite.
git clone --quiet "$work/rewrite.git" "$work/remap"
cd "$work/remap"
"$here/remap-shas.sh" "$work/rewrite.git/filter-repo/commit-map" >/dev/null 2>"$work/remap-audit.txt"
if ! git diff --quiet; then
  git commit --quiet -am 'Commit ids cited in docs and scripts follow the history rewrite' \
    -m 'Generated by scripts/history-slim/remap-shas.sh from git filter-repo'"'"'s commit-map; the pre-rewrite ids remain in drawing_board-pre-slim.bundle.'
  git push --quiet origin HEAD:main
fi
cp "$work/rewrite.git/filter-repo/commit-map" "$work/commit-map.txt"

# 4. Report and the lease-protected push command.
cd "$work/rewrite.git"
before=$(git -C "$work/backup.git" count-objects -v | awk '/size-pack/ {print $2}')
after=$(git count-objects -v | awk '/size-pack/ {print $2}')
echo "pack: ${before} KiB -> ${after} KiB"
echo "abbreviated ids remapped: $(wc -l < "$work/remap-audit.txt") (listed in $work/remap-audit.txt; check each)"
echo "main tree: $(git -C "$work/backup.git" rev-parse 'main^{tree}') -> $(git rev-parse 'main^{tree}') (differs only by removed paths and the id remap)"
leases=$(while read -r sha ref; do printf ' --force-with-lease=%s:%s' "$ref" "$sha"; done < "$work/pre-slim-refs.txt")
echo
# --atomic: if any lease fails (someone pushed during the freeze), no ref moves at all.
echo "Push (runbook step 6), from $work/rewrite.git:"
echo "  git push --atomic$leases \\"
echo "    https://github.com/CardBoardStudio/drawing_board.git 'refs/heads/*:refs/heads/*' 'refs/tags/*:refs/tags/*'"
