#!/usr/bin/env node
// Writes everything drawn from prototypes/galactic-reach/icons.js, the one source of the twenty
// star icons, that cannot read it at run time:
//   design/icons/<name>.svg, <name>.small.svg   standalone files for the design tools, one per
//                                               icon and rendering, in the palette's colours
//   prototypes/galactic-reach/rulebook.html     its sprite (the docs site runs no scripts), between
//                                               the icons:begin and icons:end markers
//   node scripts/icons.cjs           write them
//   node scripts/icons.cjs --check   fail if any is out of date (scripts/check-icons.cjs runs this)
'use strict';
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const icons = require('../prototypes/galactic-reach/icons.js');
const RULEBOOK = 'prototypes/galactic-reach/rulebook.html';
const EXPORTS = 'design/icons';
const BEGIN = '<!-- icons:begin (generated by scripts/icons.cjs from icons.js) -->';
const END = '<!-- icons:end -->';

// Exports carry fixed colours (a design file cannot read CSS): the resources in their own
// colours, Limit in gold as on the mat, everything else in the table's text colour.
const palette = fs.readFileSync(path.join(root, 'prototypes/galactic-reach/palette.css'), 'utf8');
const colour = name => palette.match(new RegExp(`--${name}:\\s*(#[0-9a-f]{6})\\s*;`, 'i'))[1].toLowerCase();
const COLOURS = { matter: colour('matter'), energy: colour('energy'), life: colour('biomass'), data: colour('data'), limit: colour('gold') };
const exportColour = name => COLOURS[name] || colour('text');

function exports() {
  const files = {};
  for (const name of icons.NAMES) {
    for (const small of [false, true]) {
      const color = exportColour(name);
      files[`${EXPORTS}/${name}${small ? '.small' : ''}.svg`] = icons.file(name, { small, color }).replace(/currentColor/g, color);
    }
  }
  return files;
}
function rulebook(html) {
  const a = html.indexOf(BEGIN), b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error(`${RULEBOOK} lacks the ${BEGIN} ... ${END} markers`);
  return `${html.slice(0, a + BEGIN.length)}\n${icons.sprite()}\n${html.slice(b)}`;
}
function outputs() {
  return { ...exports(), [RULEBOOK]: rulebook(fs.readFileSync(path.join(root, RULEBOOK), 'utf8')) };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const stale = [];
  const wanted = outputs();
  for (const [file, text] of Object.entries(wanted)) {
    const full = path.join(root, file);
    const current = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
    if (current === text) continue;
    if (check) stale.push(file);
    else { fs.mkdirSync(path.dirname(full), { recursive: true }); fs.writeFileSync(full, text); }
  }
  const extra = fs.existsSync(path.join(root, EXPORTS)) ? fs.readdirSync(path.join(root, EXPORTS)).filter(f => f.endsWith('.svg') && !wanted[`${EXPORTS}/${f}`]) : [];
  if (check) {
    if (stale.length || extra.length) {
      console.error(`Icons out of date; run node scripts/icons.cjs:\n  ${[...stale, ...extra.map(f => `${EXPORTS}/${f} (not an icon)`)].join('\n  ')}`);
      process.exit(1);
    }
    console.log(`Icons: ${icons.NAMES.length} icons, ${Object.keys(wanted).length - 1} design exports and the rulebook sprite are current.`);
  } else {
    for (const f of extra) fs.unlinkSync(path.join(root, EXPORTS, f));
    console.log(`Wrote ${Object.keys(wanted).length - 1} design exports and the rulebook sprite.`);
  }
}
module.exports = { outputs, EXPORTS, RULEBOOK, BEGIN, END };
